-- setores que já existem recebem a área pela sigla (mesma tabela de src/lib/areas.ts, AREA_DA_SIGLA)
UPDATE "tramite"."setores" SET "area" = CASE "sigla"
  WHEN 'GAB' THEN 'GABINETE' WHEN 'SEMAD' THEN 'ADMINISTRACAO' WHEN 'SEFAZ' THEN 'FAZENDA' WHEN 'CONTAB' THEN 'FAZENDA'
  WHEN 'TES' THEN 'FAZENDA' WHEN 'TRIB' THEN 'FAZENDA' WHEN 'COMPRAS' THEN 'COMPRAS' WHEN 'SESAU' THEN 'SAUDE'
  WHEN 'SEDUC' THEN 'EDUCACAO' WHEN 'SEMAS' THEN 'ASSISTENCIA_SOCIAL' WHEN 'SEINFRA' THEN 'INFRAESTRUTURA'
  WHEN 'SMSU' THEN 'INFRAESTRUTURA' WHEN 'SMMA' THEN 'INFRAESTRUTURA' WHEN 'CGM' THEN 'CONTROLE_INTERNO'
  WHEN 'PGM' THEN 'PROCURADORIA' WHEN 'PROT' THEN 'PROTOCOLO' END
WHERE "area" IS NULL;
